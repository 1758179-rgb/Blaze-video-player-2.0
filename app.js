let selectedItem = null;
let activeSearch = '';

function getEmbedUrl(url) {
  try {
    const parsedUrl = new URL(url);
    const match = parsedUrl.pathname.match(/^\/file\/d\/([^/]+)/);
    if (parsedUrl.hostname === 'drive.google.com' && match) {
      return `https://drive.google.com/file/d/${match[1]}/preview`;
    }
  } catch (error) {
    console.warn('Invalid media URL:', error);
  }
  return url;
}

function cardMarkup(item, type, list = false) {
  const badge = item.status || (type === 'movie' ? 'Movie' : 'Series');
  const meta = type === 'movie' ? 'FILM' : (item.year ? `TV · ${item.year}` : 'TV');
  const episodeInfo = type === 'movie' ? 'Movie' : `${item.episodes.length} episodes`;
  return `
    <button class="series-card ${list ? 'airing-card' : ''}" type="button" data-id="${item.id}" data-type="${type}" aria-label="Open ${item.title}">
      <span class="series-poster" style="background-image: linear-gradient(180deg, transparent 38%, rgba(7, 8, 12, .88)), url('${item.image}')"></span>
      <span class="series-card-info">
        <strong>${item.title}</strong>
        <span class="card-metadata"><span>${meta}</span><span>${item.year || ''}</span><span>CC ${item.episodes.length}</span><span>★ ${Number(item.rating).toFixed(1)}</span></span>
        ${list ? `<small class="airing-description">${badge} · ${item.subtitle}</small>` : `<small>${episodeInfo} · ${item.subtitle}</small>`}
      </span>
      ${list ? '<span class="airing-dot" aria-hidden="true"></span>' : `<span class="catalog-badge">${badge}</span>`}
    </button>`;
}

function attachCardEvents() {
  document.querySelectorAll('.series-card[data-id]').forEach((card) => {
    card.onclick = () => {
      const collection = card.dataset.type === 'movie' ? movies : series;
      openMedia(collection.find((item) => item.id === card.dataset.id), card.dataset.type);
    };
  });
}

function openMedia(item, type = 'series') {
  if (!item) return;
  selectedItem = item;
  watchSection.hidden = false;
  watchTitle.textContent = item.title;
  watchSubtitle.textContent = item.subtitle || (type === 'movie' ? 'MOVIE' : 'ANIME');
  videoTitle.textContent = 'Select a video to start watching';
  videoPlayer.src = 'about:blank';
  playerPlaceholder.hidden = false;
  playlistHeading.firstChild.textContent = type === 'movie' ? 'Movie' : 'Episodes';
  episodeCount.textContent = `${item.episodes.length} ${type === 'movie' ? 'video' : 'episodes'}`;
  episodeList.innerHTML = item.episodes.map((episode) => `
    <button class="episode-choice" type="button" data-episode-id="${episode.id}" aria-pressed="false">
      <span class="episode-number">${String(episode.id).padStart(2, '0')}</span>
      <span class="episode-choice-copy"><span class="episode-choice-title">${episode.title}</span>${episode.caption ? `<span class="episode-caption">${episode.caption}</span>` : ''}</span>
      <span class="episode-choice-play" aria-hidden="true">▶</span>
    </button>`).join('');

  episodeList.querySelectorAll('.episode-choice').forEach((button, index) => {
    button.onclick = () => playEpisode(item.episodes[index]);
  });
  document.querySelectorAll('.series-card[data-id]').forEach((card) => {
    card.classList.toggle('selected', card.dataset.id === item.id);
  });
  watchSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function playEpisode(episode) {
  if (!selectedItem || !episode || !videoPlayer) return;
  videoPlayer.src = getEmbedUrl(episode.url);
  videoTitle.textContent = `${selectedItem.title} — ${episode.title}`;
  playerPlaceholder.hidden = true;
  episodeList.querySelectorAll('.episode-choice').forEach((button) => {
    const active = Number(button.dataset.episodeId) === episode.id;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

function matchesSearch(item) {
  if (!activeSearch) return true;
  const haystack = `${item.title} ${item.subtitle || ''} ${item.year || ''} ${item.status || ''}`.toLowerCase();
  return haystack.includes(activeSearch);
}

function renderCatalog() {
  const visibleSeries = series.filter(matchesSearch);
  const visibleMovies = movies.filter(matchesSearch);
  const topAiring = visibleSeries.filter((item) => item.id === 'one-piece' || item.status === 'Airing');
  const popular = visibleSeries.filter((item) => item.popular || item.id === 'cyberpunk-edgerunners-season-2').sort((a, b) => b.rating - a.rating);

  topAiringGrid.innerHTML = topAiring.length
    ? topAiring.map((item) => cardMarkup(item, 'series', true)).join('')
    : '<p class="empty-state">No airing titles match your search.</p>';
  popularGrid.innerHTML = popular.length
    ? popular.map((item) => cardMarkup(item, 'series')).join('')
    : '<p class="empty-state">No popular titles match your search.</p>';
  seriesGrid.innerHTML = visibleSeries.length
    ? visibleSeries.map((item) => cardMarkup(item, 'series')).join('')
    : '<p class="empty-state">No anime series match your search.</p>';
  movieGrid.innerHTML = visibleMovies.length
    ? visibleMovies.map((item) => cardMarkup(item, 'movie')).join('')
    : '<p class="empty-state">No movies match your search.</p>';
  attachCardEvents();
  searchStatus.textContent = activeSearch ? `${visibleSeries.length + visibleMovies.length} matching titles` : '';
}

function setSearch(value) {
  activeSearch = value.trim().toLowerCase();
  renderCatalog();
}

if (searchInput) searchInput.addEventListener('input', () => setSearch(searchInput.value));
if (searchForm) searchForm.addEventListener('submit', (event) => { event.preventDefault(); setSearch(searchInput.value); });
if (searchButton) searchButton.addEventListener('click', () => searchInput.focus());
if (menuButton) menuButton.addEventListener('click', () => document.getElementById('top-airing').scrollIntoView({ behavior: 'smooth' }));
if (randomButton) randomButton.addEventListener('click', () => {
  const choices = series.filter((item) => item.id !== 'cyberpunk-edgerunners-season-2' || item.episodes.length);
  const choice = choices[Math.floor(Math.random() * choices.length)];
  openMedia(choice, 'series');
});
if (featuredButton) featuredButton.addEventListener('click', () => openMedia(series.find((item) => item.id === 'cyberpunk-edgerunners-season-2'), 'series'));

document.addEventListener('keydown', (event) => {
  if (event.key === '/' && !['INPUT', 'TEXTAREA'].includes(document.activeElement.tagName)) {
    event.preventDefault();
    searchInput.focus();
  }
});

renderCatalog();
