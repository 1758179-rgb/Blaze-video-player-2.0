const episodeCount = document.getElementById('episodeCount');
const playlistHeading = document.getElementById('playlistHeading');
const themeButtons = document.querySelectorAll('.theme-button');
let selectedSeries = null;

function getEmbedUrl(url) {
  try {
    const parsedUrl = new URL(url);
    const match = parsedUrl.pathname.match(/^\/file\/d\/([^/]+)/);
    if (parsedUrl.hostname === 'drive.google.com' && match) return `https://drive.google.com/file/d/${match[1]}/preview`;
  } catch (error) {
    console.warn('Invalid video URL:', error);
  }
  return url;
}

function setTheme(theme) {
  document.body.dataset.theme = theme;
  themeButtons.forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.setTheme === theme));
  });
}

function playEpisode(episode) {
  if (!selectedSeries || !videoPlayer) return;
  videoPlayer.src = getEmbedUrl(episode.url);
  videoTitle.textContent = `${selectedSeries.title} — ${episode.title}`;
  playerPlaceholder.hidden = true;
  episodeList.querySelectorAll('.episode-choice').forEach((button) => {
    const active = Number(button.dataset.episodeId) === episode.id;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}

function openMedia(show, mediaType = 'series') {
  if (!show) return;
  selectedSeries = show;
  watchSection.hidden = false;
  watchSeriesTitle.textContent = show.title;
  watchSeriesSubtitle.textContent = show.subtitle;
  videoTitle.textContent = 'Select a video to start watching';
  videoPlayer.src = 'about:blank';
  playerPlaceholder.hidden = false;
  playlistHeading.firstChild.textContent = mediaType === 'movie' ? 'Movie' : 'Episodes';
  episodeCount.textContent = `${show.episodes.length} ${show.episodes.length === 1 ? 'video' : 'videos'}`;

  episodeList.innerHTML = show.episodes.map((episode) => `
    <button class="episode-choice" type="button" data-episode-id="${episode.id}" aria-pressed="false">
      <span class="episode-number">${String(episode.id).padStart(2, '0')}</span>
      <span class="episode-choice-copy">
        <span class="episode-choice-title">${episode.title}</span>
        ${episode.caption ? `<span class="episode-caption">${episode.caption}</span>` : ''}
      </span>
      <span class="episode-choice-play" aria-hidden="true">▶</span>
    </button>
  `).join('');

  episodeList.querySelectorAll('.episode-choice').forEach((button, index) => {
    button.addEventListener('click', () => playEpisode(show.episodes[index]));
  });

  document.querySelectorAll('.series-card').forEach((card) => {
    card.classList.toggle('selected', card.dataset.mediaId === show.id && card.dataset.mediaType === mediaType);
  });
  watchSection.scrollIntoView({ behavior: 'smooth', block: 'start' });
}

function renderCards(items, grid, mediaType) {
  if (!grid) return;
  grid.innerHTML = items.map((item) => `
    <button class="series-card" type="button" data-media-id="${item.id}" data-media-type="${mediaType}" aria-label="Open ${item.title}">
      <span class="series-poster ${item.poster}" style="--series-accent: ${item.accent}; background-image: linear-gradient(180deg, transparent 40%, rgba(5, 5, 10, .88)), url('${item.image}')"></span>
      <span class="series-card-info">
        <strong>${item.title}</strong>
        <small>${mediaType === 'movie' ? 'Movie' : `${item.episodes.length} episodes`} · ${item.subtitle}</small>
      </span>
    </button>
  `).join('');
  grid.querySelectorAll('.series-card').forEach((card) => {
    card.addEventListener('click', () => openMedia(items.find((item) => item.id === card.dataset.mediaId), mediaType));
  });
}

